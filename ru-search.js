const ruClean = s => String(s).toLowerCase().replace(/ё/g, "е");
const RU_END = /(ами|ями|ого|его|ому|ему|ыми|ими|ов|ев|ей|ой|ый|ий|ая|яя|ое|ее|ые|ие|ую|юю|ам|ям|ах|ях|ом|ем|а|я|ы|и|у|ю|е|о|ь)$/;
// Основа русского слова: «пружины» → «пружин», «рамку» → «рамк»
function ruStem(w) {
  if (!/^[а-я]+$/.test(w)) return w;
  const m = w.match(RU_END);
  return m && w.length - m[0].length >= 3 ? w.slice(0, -m[0].length) : w;
}
const RU_WORDS = new Map(), RU_PHRASES = [], RU_ALL = [];
RU_DICT.forEach(([latin, ru]) => {
  const alts = latin.split("|");
  ru.split(",").map(k => ruClean(k.trim())).forEach(k => {
    RU_ALL.push([k.replace(/-/g, ""), alts]);
    if (k.includes(" ")) RU_PHRASES.push([k, alts]);
    else RU_WORDS.set(ruStem(k.replace(/-/g, "")), alts);
  });
});
RU_PHRASES.sort((a, b) => b[0].length - a[0].length);
RU_PHRASES.forEach(p => { p[2] = new RegExp("(^|\\s)" + p[0].replace(/[.*+?^${}()|[\]\\]/g, "\\$&") + "[а-я]*(?=\\s|$)", "g"); });

// Служебные слова не ищем: «амортизаторы на камри», «стойки для филдера», «купить колодки» (12.11.2026)
const RU_SKIP = new Set(["на", "для", "в", "во", "от", "к", "ко", "с", "со", "по", "под", "и", "или", "а", "у", "из", "ли", "мне",
  "купить", "куплю", "цена", "цены", "стоимость", "нужен", "нужна", "нужно", "нужны", "есть", "подешевле", "недорого"]);

// Запрос → список слов; у каждого слова варианты написания. Товар подходит, если нашлось по варианту каждого слова.
function searchTerms(query) {
  let q = ruClean(query);
  const terms = [];
  RU_PHRASES.forEach(([, alts, re]) => { q = q.replace(re, () => { terms.push(alts); return " "; }); });
  q.split(/\s+/).filter(w => w && !RU_SKIP.has(w)).forEach(w => {
    const key = ruStem(w.replace(/-/g, ""));
    const alts = RU_WORDS.get(key);
    terms.push([ruStem(w), ...(alts || [])]);
  });
  return terms;
}

// Для подсказок при вводе: «кам» → ["camry"]
function ruGuess(q) {
  q = ruClean(q).trim().replace(/-/g, "");
  if (q.length < 2) return [];
  return [...new Set(RU_ALL.filter(([k]) => k.startsWith(q)).flatMap(([, alts]) => alts))];
}
